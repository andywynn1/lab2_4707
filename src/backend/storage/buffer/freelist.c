#define INT_ACCESS_ONCE(var)	((int)(*((volatile int *)&(var))))


/*
 * The shared freelist control information.
 */
typedef struct
{
	/* Spinlock: protects the values below */
	slock_t		buffer_strategy_lock;

	/*
	 * Clock sweep hand: index of next buffer to consider grabbing. Note that
	 * this isn't a concrete buffer - we only ever increase the value. So, to
	 * get an actual buffer, it needs to be used modulo NBuffers.
	 */
	pg_atomic_uint32 nextVictimBuffer;

	int			firstFreeBuffer;	/* Head of list of unused buffers */
	int			lastFreeBuffer; /* Tail of list of unused buffers */

	/*
	 * NOTE: lastFreeBuffer is undefined when firstFreeBuffer is -1 (that is,
	 * when the list is empty)
	 */

	/*
	 * Statistics.  These counters should be wide enough that they can't
	 * overflow during a single bgwriter cycle.
	 */
	uint32		completePasses; /* Complete cycles of the clock sweep */
	pg_atomic_uint32 numBufferAllocs;	/* Buffers allocated since last reset */

	/*
	 * Bgworker process to be notified upon activity or -1 if none. See
	 * StrategyNotifyBgWriter.
	 */
	int			bgwprocno;

	/*
	 * Second-LRU: global access counter. A buffer gets the current value as
	 * its last_access when it is requested, then the counter is incremented.
	 */
	pg_atomic_uint64 lastAccessCounter;
} BufferStrategyControl;

/* Pointers to shared state */
static BufferStrategyControl *StrategyControl = NULL;

/*
 * Private (non-shared) state for managing a ring of shared buffers to re-use.
 * This is currently the only kind of BufferAccessStrategy object, but someday
 * we might have more kinds.
 */
typedef struct BufferAccessStrategyData
{
	/* Overall strategy type */
	BufferAccessStrategyType btype;
	/* Number of elements in buffers[] array */
	int			nbuffers;

	/*
	 * Index of the "current" slot in the ring, ie, the one most recently
	 * returned by GetBufferFromRing.
	 */
	int			current;

	/*
	 * Array of buffer numbers.  InvalidBuffer (that is, zero) indicates we
	 * have not yet selected a buffer for this ring slot.  For allocation
	 * simplicity this is palloc'd together with the fixed fields of the
	 * struct.
	 */
	Buffer		buffers[FLEXIBLE_ARRAY_MEMBER];
}			BufferAccessStrategyData;


/*
 * have_free_buffer -- a lockless check to see if there is a free buffer in
 *					   buffer pool.
 *
 * If the result is true that will become stale once free buffers are moved out
 * by other operations, so the caller who strictly want to use a free buffer
 * should not call this.
 */
bool
have_free_buffer(void)
{
	if (StrategyControl->firstFreeBuffer >= 0)
		return true;
	else
		return false;
}

/*
 * StrategyNextTimestamp
 *
 *	Second-LRU: return the current value of the global access counter and
 *	advance it by one. Callers store the returned value in buf->last_access.
 */
uint64
StrategyNextTimestamp(void)
{
	return pg_atomic_fetch_add_u64(&StrategyControl->lastAccessCounter, 1);
}

/*
 * StrategyCurrentTimestamp
 *
 *	Second-LRU: read the global access counter without advancing it.
 */
uint64
StrategyCurrentTimestamp(void)
{
	return pg_atomic_read_u64(&StrategyControl->lastAccessCounter);
}

/* qsort comparator: oldest timestamp first, ties broken by buffer id */
static int
candidate_cmp(const void *a, const void *b)
{
	const CandidateBuf *ca = (const CandidateBuf *) a;
	const CandidateBuf *cb = (const CandidateBuf *) b;

	if (ca->last_access < cb->last_access)
		return -1;
	if (ca->last_access > cb->last_access)
		return 1;
	if (ca->buf_id < cb->buf_id)
		return -1;
	if (ca->buf_id > cb->buf_id)
		return 1;
	return 0;
}

/*
 * StrategyGetBuffer
 *
 *	Called by the bufmgr to get the next candidate buffer to use in
 *	BufferAlloc(). Second-LRU policy: among all unpinned buffers, pick the
 *	one with the second smallest last_access. If only one unpinned buffer
 *	exists, pick it.
 *
 *	The buffer access strategy ring, the free list and the clock sweep are
 *	not used, so the policy applies to every allocation.
 *
 *	To ensure that no one else can pin the buffer before we do, we must
 *	return the buffer with the buffer header spinlock still held.
 */
BufferDesc *
StrategyGetBuffer(BufferAccessStrategy strategy, uint32 *buf_state, bool *from_ring,
				  BufferSelectionSnapshot *snapshot)
{
	BufferDesc *buf;
	int			bgwprocno;
	uint32		local_buf_state;	/* to avoid repeated (de-)referencing */
	CandidateBuf *cand;
	int			ncand;
	int			victim_idx;
	int			i;

	*from_ring = false;

	/*
	 * Wake the bgwriter if asked, exactly as the original code does.
	 */
	bgwprocno = INT_ACCESS_ONCE(StrategyControl->bgwprocno);
	if (bgwprocno != -1)
	{
		/* reset bgwprocno first, before setting the latch */
		StrategyControl->bgwprocno = -1;
		SetLatch(&ProcGlobal->allProcs[bgwprocno].procLatch);
	}

	/* The bgwriter uses this count to estimate buffer consumption. */
	pg_atomic_fetch_add_u32(&StrategyControl->numBufferAllocs, 1);

	cand = (CandidateBuf *) palloc(NBuffers * sizeof(CandidateBuf));

	for (;;)
	{
		CHECK_FOR_INTERRUPTS();
		snapshot->now = StrategyCurrentTimestamp();

		/* Collect every unpinned buffer with its timestamp. */
		ncand = 0;
		for (i = 0; i < NBuffers; i++)
		{
			buf = GetBufferDescriptor(i);

			local_buf_state = LockBufHdr(buf);
			if (BUF_STATE_GET_REFCOUNT(local_buf_state) == 0)
			{
				cand[ncand].buf_id = i;
				cand[ncand].last_access = buf->last_access;
				ncand++;
			}
			UnlockBufHdr(buf, local_buf_state);
		}

		/* Discard the scan if any buffer was accessed while collecting it. */
		if (StrategyCurrentTimestamp() != snapshot->now)
			continue;

		if (ncand == 0)
		{
			pfree(cand);
			elog(ERROR, "no unpinned buffers available");
		}

		/* Oldest first. */
		qsort(cand, ncand, sizeof(CandidateBuf), candidate_cmp);

		/* Second least recently used, or the only one if there is just one. */
		victim_idx = (ncand >= 2) ? 1 : 0;

		/*
		 * Lock the chosen buffer and make sure nobody pinned it since the
		 * scan. Also retry if it was accessed and unpinned in the meantime.
		 */
		buf = GetBufferDescriptor(cand[victim_idx].buf_id);
		local_buf_state = LockBufHdr(buf);
		if (BUF_STATE_GET_REFCOUNT(local_buf_state) == 0 &&
			buf->last_access == cand[victim_idx].last_access &&
			StrategyCurrentTimestamp() == snapshot->now)
		{
			/* No allocation, logging, or freeing while the spinlock is held. */
			snapshot->candidates = cand;
			snapshot->ncandidates = ncand;
			snapshot->victim_index = victim_idx;
			*buf_state = local_buf_state;
			return buf;
		}
		UnlockBufHdr(buf, local_buf_state);
	}
}

/*
 * Emit one complete record after GetVictimBuffer has successfully claimed the
 * buffer and released all header/content locks.  The caller frees candidates.
 */
void
StrategyLogSelection(const BufferSelectionSnapshot *snapshot, Size page_space)
{
	StringInfoData output;
	uint64		victim_timestamp;
	int			i;

	initStringInfo(&output);
	for (i = 0; i < snapshot->ncandidates; i++)
		appendStringInfo(&output, "%s" UINT64_FORMAT ":" UINT64_FORMAT,
						 (i > 0) ? ", " : "",
						 snapshot->now - snapshot->candidates[i].last_access,
						 snapshot->candidates[i].last_access);

	victim_timestamp = snapshot->candidates[snapshot->victim_index].last_access;
	elog(LOG, "Candidate buffers: %s\n"
		 "Replaced buffer: " UINT64_FORMAT ":" UINT64_FORMAT "\n"
		 "Available Page Space: %zu",
		 output.data, snapshot->now - victim_timestamp, victim_timestamp,
		 page_space);
	pfree(output.data);
}

/*
 * StrategyFreeBuffer: put a buffer on the freelist
 */
void
StrategyFreeBuffer(BufferDesc *buf)
{
	SpinLockAcquire(&StrategyControl->buffer_strategy_lock);

	/*
	 * It is possible that we are told to put something in the freelist that
	 * is already in it; don't screw up the list if so.
	 */
	if (buf->freeNext == FREENEXT_NOT_IN_LIST)
	{
		buf->freeNext = StrategyControl->firstFreeBuffer;
		if (buf->freeNext < 0)
			StrategyControl->lastFreeBuffer = buf->buf_id;
		StrategyControl->firstFreeBuffer = buf->buf_id;
	}

	SpinLockRelease(&StrategyControl->buffer_strategy_lock);
}

/*
 * StrategySyncStart -- tell BufferSync where to start syncing
 *
 * The result is the buffer index of the best buffer to sync first.
 * BufferSync() will proceed circularly around the buffer array from there.
 *
 * In addition, we return the completed-pass count (which is effectively
 * the higher-order bits of nextVictimBuffer) and the count of recent buffer
 * allocs if non-NULL pointers are passed.  The alloc count is reset after
 * being read.
 */
int
StrategySyncStart(uint32 *complete_passes, uint32 *num_buf_alloc)
{
	uint32		nextVictimBuffer;
	int			result;

	SpinLockAcquire(&StrategyControl->buffer_strategy_lock);
	nextVictimBuffer = pg_atomic_read_u32(&StrategyControl->nextVictimBuffer);
	result = nextVictimBuffer % NBuffers;

	if (complete_passes)
	{
		*complete_passes = StrategyControl->completePasses;

		/*
		 * Additionally add the number of wraparounds that happened before
		 * completePasses could be incremented. C.f. ClockSweepTick().
		 */
		*complete_passes += nextVictimBuffer / NBuffers;
	}

	if (num_buf_alloc)
	{
		*num_buf_alloc = pg_atomic_exchange_u32(&StrategyControl->numBufferAllocs, 0);
	}
	SpinLockRelease(&StrategyControl->buffer_strategy_lock);
	return result;
}

/*
 * StrategyNotifyBgWriter -- set or clear allocation notification latch
 *
 * If bgwprocno isn't -1, the next invocation of StrategyGetBuffer will
 * set that latch.  Pass -1 to clear the pending notification before it
 * happens.  This feature is used by the bgwriter process to wake itself up
 * from hibernation, and is not meant for anybody else to use.
 */
void
StrategyNotifyBgWriter(int bgwprocno)
{
	/*
	 * We acquire buffer_strategy_lock just to ensure that the store appears
	 * atomic to StrategyGetBuffer.  The bgwriter should call this rather
	 * infrequently, so there's no performance penalty from being safe.
	 */
	SpinLockAcquire(&StrategyControl->buffer_strategy_lock);
	StrategyControl->bgwprocno = bgwprocno;
	SpinLockRelease(&StrategyControl->buffer_strategy_lock);
}


/*
 * StrategyShmemSize
 *
 * estimate the size of shared memory used by the freelist-related structures.
 *
 * Note: for somewhat historical reasons, the buffer lookup hashtable size
 * is also determined here.
 */
Size
StrategyShmemSize(void)
{
	Size		size = 0;

	/* size of lookup hash table ... see comment in StrategyInitialize */
	size = add_size(size, BufTableShmemSize(NBuffers + NUM_BUFFER_PARTITIONS));

	/* size of the shared replacement strategy control block */
	size = add_size(size, MAXALIGN(sizeof(BufferStrategyControl)));

	return size;
}

/*
 * StrategyInitialize -- initialize the buffer cache replacement
 *		strategy.
 *
 * Assumes: All of the buffers are already built into a linked list.
 *		Only called by postmaster and only during initialization.
 */
void
StrategyInitialize(bool init)
{
	bool		found;

	/*
	 * Initialize the shared buffer lookup hashtable.
	 *
	 * Since we can't tolerate running out of lookup table entries, we must be
	 * sure to specify an adequate table size here.  The maximum steady-state
	 * usage is of course NBuffers entries, but BufferAlloc() tries to insert
	 * a new entry before deleting the old.  In principle this could be
	 * happening in each partition concurrently, so we could need as many as
	 * NBuffers + NUM_BUFFER_PARTITIONS entries.
	 */
	InitBufTable(NBuffers + NUM_BUFFER_PARTITIONS);

	/*
	 * Get or create the shared strategy control block
	 */
	StrategyControl = (BufferStrategyControl *)
		ShmemInitStruct("Buffer Strategy Status",
						sizeof(BufferStrategyControl),
						&found);

	if (!found)
	{
		/*
		 * Only done once, usually in postmaster
		 */
		Assert(init);

		SpinLockInit(&StrategyControl->buffer_strategy_lock);

		/*
		 * Grab the whole linked list of free buffers for our strategy. We
		 * assume it was previously set up by InitBufferPool().
		 */
		StrategyControl->firstFreeBuffer = 0;
		StrategyControl->lastFreeBuffer = NBuffers - 1;

		/* Initialize the clock sweep pointer */
		pg_atomic_init_u32(&StrategyControl->nextVictimBuffer, 0);

		/* Clear statistics */
		StrategyControl->completePasses = 0;
		pg_atomic_init_u32(&StrategyControl->numBufferAllocs, 0);

		/* No pending notification */
		StrategyControl->bgwprocno = -1;

		/* Reserve 0 for buffers that have never been accessed. */
		pg_atomic_init_u64(&StrategyControl->lastAccessCounter, 1);
	}
	else
		Assert(!init);
}


